/** Source of the generated declaration file that registers `paths` with `@chanom/router`. */
export default function generateTypes(paths: readonly string[]): string {
  const union = paths.length === 0 ? ' never' : paths.map((path) => `\n      | '${path}'`).join('');
  return `// Generated by @chanom/router. Do not edit: it is rewritten whenever pages change.

declare module '@chanom/router' {
  interface Register {
    paths:${union};
  }
}

export {};
`;
}
