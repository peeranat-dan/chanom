import { describe, expect, it } from 'vitest';

import { generateTypes } from '../../src/vite/generate-types.ts';

describe('generateTypes', () => {
  it('registers the paths as a union', () => {
    expect(generateTypes(['/', '/posts/:id']))
      .toBe(`// Generated by @chanom/router. Do not edit: it is rewritten whenever pages change.

declare module '@chanom/router' {
  interface Register {
    paths:
      | '/'
      | '/posts/:id';
  }
}

export {};
`);
  });

  it('registers never when there are no pages', () => {
    expect(generateTypes([])).toContain('paths: never;');
  });
});
